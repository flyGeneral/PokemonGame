# ---------------------------------------------------------------- 经验/等级
def exp_for_level(level):
    """中等快速曲线:累计经验 = L^3。"""
    return level ** 3

def exp_to_next(level):
    return exp_for_level(level + 1) - exp_for_level(level)

def exp_gain(enemy, trainer_battle):
    base = SPECIES[enemy.species]["base_exp"]
    g = base * enemy.level // 7
    return int(g * 1.5) if trainer_battle else g
